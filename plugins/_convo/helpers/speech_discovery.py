"""Speech output discovery and Test connection, run only on an explicit user action against the configured speech output.

Native Kokoro: nothing is contacted. Convo's managed audio.cpp: its supervisor's model, voice and tuning reads through the managed
runtime, and nothing at all while that runtime is off. Every other provider: read-only GETs from READ_ROUTES only, in the order
its plan lists them; nothing is loaded, switched, unloaded, selected or synthesized, and no other route is ever requested. The
user's own audio.cpp server is never sent a model-switch, load or unload command: its loaded model and its current tuning
selection are shown exactly as the server reports them.

What the server answered is returned route by route (`checks`), so a provider whose speech route is undocumented (llama.cpp,
Unsloth Studio) is reported as it really is. A speech route is recognised by how it answers a read-only GET (a POST-only route
answers 405); "ready" never means speech was produced: no audio is generated here. This module keeps its own bounded GET
(`_probe`, the same limits as the settings module's) because it must report statuses; `fetch` is accepted for the shared call
signature and is not used for speech.
"""
from __future__ import annotations

import json
from urllib.parse import urlsplit

import httpx

from . import convo_net
from .convo_contract import ContractError, credentials, endpoint
from .speech_providers import PROVIDERS, effective_provider, per

READ_ROUTES = ('/models', '/backend/models', '/voices', '/tuning/profiles', '/audio/speech')   # GET only
PLANS = {
    'audiocpp': ('/models', '/backend/models', '/voices', '/tuning/profiles', '/audio/speech'),
    'speech_route': ('/models', '/voices', '/audio/speech'),
    'models': ('/models',),
}
ROUTE_PRESENT = (200, 400, 405, 415, 422)        # how an existing (POST) speech route answers a read-only GET
LIMIT = 2 * 1024 ** 2
NO_FALLBACK = 'Connection could not be verified. Check the endpoint, credentials and running service; no fallback was used.'
NO_AUDIO = 'No audio was generated by this check.'


def _client():
    return convo_net.client(8)


async def _probe(url, headers):
    """One read-only GET. Returns what the server answered ({status, data, error}); never raises, never follows a redirect, reads
    a body only from a 200 answer and at most LIMIT bytes of it."""
    try:
        async with _client() as client:
            async with client.stream('GET', url, headers=headers) as response:
                status = response.status_code
                if status != 200:
                    return {'status': status, 'data': None, 'error': ''}
                chunks, size = [], 0
                async for chunk in response.aiter_bytes():
                    size += len(chunk)
                    if size > LIMIT:
                        return {'status': status, 'data': None, 'error': 'too_large'}
                    chunks.append(chunk)
                try:
                    return {'status': status, 'data': json.loads(b''.join(chunks)), 'error': ''}
                except ValueError:
                    return {'status': status, 'data': None, 'error': 'not_json'}
    except httpx.TimeoutException as failure:
        return {'status': None, 'data': None, 'error': 'timeout', 'failure': failure}
    except httpx.HTTPError as failure:
        return {'status': None, 'data': None, 'error': 'unreachable', 'failure': failure}


def _count(data, fields, noun):
    if isinstance(data, dict):
        for field in fields:
            if isinstance(data.get(field), (list, dict)):
                data = data[field]
                break
    number = len(data) if isinstance(data, (list, dict)) else 0
    return 'lists ' + str(number) + ' ' + noun + ('' if number == 1 else 's')


def _answer_text(route, answer):
    status, data, error = answer['status'], answer['data'], answer['error']
    if status is None:
        code = convo_net.failure_code(answer['failure']) if answer.get('failure') is not None else ('timeout' if error == 'timeout' else '')
        return {'timeout': 'no answer within 8 s', 'refused': 'nothing listening (connection refused)', 'unknown_host': 'name not found',
                'certificate_changed': 'certificate changed', 'certificate_untrusted': 'certificate not trusted'}.get(code, 'no answer')
    if route == '/audio/speech':
        if status == 404:
            return 'no speech route here'
        if status == 405:
            return 'speech route present (it takes POST requests)'
        if status in ROUTE_PRESENT:
            return 'speech route present (it answered a request without text)'
    if status in (401, 403):
        return 'refused: a key is required or was not accepted'
    if status == 404:
        return 'not offered by this server'
    if status != 200:
        return 'answered HTTP ' + str(status)
    if error:
        return {'not_json': 'answered, but not with JSON', 'too_large': 'answer too large; ignored'}.get(error, error)
    if route == '/models':
        return _count(data, ('data', 'models', 'available_models'), 'model')
    if route == '/backend/models' and isinstance(data, dict):
        return 'current model ' + str(data.get('current') or 'none') + ' (' + str(data.get('state') or 'unknown') + ')'
    if route == '/voices':
        return _count(data, ('data', 'voices'), 'voice')
    if route == '/tuning/profiles' and isinstance(data, dict):
        return 'current tuning ' + (_tuning(data)['label'] if _tuning(data) else 'not reported')
    return 'answered'


def _voices(data):
    """A voice listed with a `voice` field (audio.cpp: id '2098c329bc9d', voice 'clone:2098c329bc9d') is selected by that value."""
    items = data
    if isinstance(data, dict):
        items = next((data[field] for field in ('data', 'voices') if isinstance(data.get(field), list)), [])
    if not isinstance(items, list):
        return {'data': []}
    return {'data': [dict(item, id=item['voice']) if isinstance(item, dict) and isinstance(item.get('voice'), str) and item['voice'] else item
                     for item in items]}


def _tuning(document):
    """The server's own current tuning selection (its realtime surface first) as {id, label}, or None."""
    profiles = document.get('profiles') if isinstance(document.get('profiles'), dict) else {}
    for holder in ((document.get('selections') or {}).get('realtime') if isinstance(document.get('selections'), dict) else None, document.get('selected')):
        if isinstance(holder, dict):
            for value in holder.values():
                if isinstance(value, str) and value:
                    profile = profiles.get(value) if isinstance(profiles.get(value), dict) else {}
                    return {'id': value, 'label': str(profile.get('name') or profile.get('label') or value)[:200]}
    return None


async def discover(role, fetch, options):
    """Models, voices and tuning profiles for `role` (roles.tts, normalized, with its private key attached), route-by-route
    `checks`, the audio.cpp server's own state (`server`) and a verification state."""
    result = {'ok': True, 'models': [], 'voices': [], 'tuning': [], 'warnings': [], 'checks': []}
    provider, connection = effective_provider(role)
    kind = per(PROVIDERS[provider]['verify'], connection)
    try:
        if kind == 'native':
            verification = {'state': 'unverified', 'message': 'Uses native Kokoro voice controls. This check does not load or synthesize a model.'}
            result['warnings'].append('Select and verify Kokoro using the native speech settings.')
        elif kind == 'managed':
            verification = await _managed(role, result, options)
        else:
            verification = await _external(role, result, options, provider, kind)
    except ContractError as error:                                  # Convo's own refusal (address or credential reference): say which
        verification = {'state': 'unavailable', 'message': str(error) + ' Nothing was contacted.'}
    except (ValueError, httpx.HTTPError, KeyError):
        verification = {'state': 'unavailable', 'message': NO_FALLBACK}
    result['verification'] = verification
    return result


async def _managed(role, result, options):
    from .convo_transport import Sidecar
    from .convo_service import settings
    saved = settings()
    if not saved['sidecar'].get('managed'):
        return {'state': 'unavailable', 'message': 'Convo’s managed runtime is off: turn on “Manage runtime” and save, then check again. Nothing was contacted.'}
    sidecar = Sidecar(saved['sidecar'])
    models = await sidecar.studio({'operation': 'models'})
    result['models'] = options(models, ('available', 'available_models', 'models', 'data'))
    profiles = await sidecar.studio({'operation': 'profiles'})
    voices = options(profiles, ('voices', 'profiles'))
    result['voices'] = [{'id': v['id'] if v['id'].startswith('clone:') else 'clone:' + v['id'], 'label': v['label']} for v in voices]
    tuning = await sidecar.studio({'operation': 'tuning'})
    result['tuning'] = options(tuning, ('profiles',))
    loaded = role.get('model') in models.get('loaded_models', [])
    return {'state': 'ready' if loaded else 'unverified', 'message': 'Managed audio responded; selected model is loaded.' if loaded else 'Managed audio responded; selected model must be explicitly loaded.'}


async def _external(role, result, options, provider, kind):
    label = PROVIDERS[provider]['label']
    if not (role.get('url') or '').strip():
        return {'state': 'unavailable', 'message': 'Enter the ' + label + ' server URL first' +
                (': Unsloth Studio has no documented default address.' if provider == 'unsloth_studio' else '.') + ' Nothing was contacted.'}
    url, headers = endpoint(role), credentials(role)
    if kind == 'models' and not headers:
        return {'state': 'unavailable', 'message': 'No OpenAI key: add one in Agent Zero’s API keys, or choose a key for Convo only. Nothing was sent.'}
    answers = {}
    for route in PLANS[kind]:
        answer = answers[route] = await _probe(url + route, headers)
        result['checks'].append({'path': urlsplit(url + route).path, 'status': answer['status'], 'answer': _answer_text(route, answer)})
        if answer['status'] is None:
            break                                                  # no answer: the remaining routes are not tried
    first = answers[PLANS[kind][0]]
    ok = lambda route: route in answers and answers[route]['status'] == 200 and answers[route]['data'] is not None
    if first['status'] is None:
        if first.get('failure') is None:
            return {'state': 'unavailable', 'message': 'No answer from ' + url + '. ' + NO_FALLBACK}
        result['_failure'] = first['failure']                       # for the card's hints; never part of the answer
        return {'state': 'unavailable', 'message': convo_net.describe(first['failure'], url)[1] + ' Nothing else was tried; no fallback was used.'}
    if kind == 'models':
        if first['status'] in (401, 403):
            return {'state': 'unavailable', 'message': label + ' refused the key (HTTP ' + str(first['status']) + '). Check Agent Zero’s OpenAI API key.'}
        if not ok('/models'):
            return {'state': 'unavailable', 'message': label + ' answered HTTP ' + str(first['status']) + '. ' + NO_FALLBACK}
        listed = {item['id'] for item in options(first['data'], ('data', 'models'))}
        model = role.get('model') or ''
        if model in listed:
            return {'state': 'ready', 'message': label + ' accepted the key and lists ' + model + '. ' + NO_AUDIO}
        return {'state': 'unverified', 'message': label + ' accepted the key but does not list ' + (model or 'a model') + ' for this account. ' + NO_AUDIO}
    if first['status'] in (401, 403):
        return {'state': 'unavailable', 'message': 'The server refused: it needs a key, or did not accept it (HTTP ' + str(first['status']) + '). ' + NO_FALLBACK}
    models = options(first['data'], ('data', 'models', 'available_models')) if ok('/models') else []
    server = None
    if ok('/backend/models') and isinstance(answers['/backend/models']['data'], dict):
        state = answers['/backend/models']['data']
        seen = {item['id'] for item in models}
        models += [item for item in options(state, ('available',)) if item['id'] not in seen]
        current = state.get('current') if isinstance(state.get('current'), str) else ''
        loaded = state.get('state') == 'loaded' and current in (state.get('loaded_models') or [])
        server = {'model': current, 'loaded': loaded, 'state': str(state.get('state') or '')}
    result['models'] = models
    if ok('/voices'):
        result['voices'] = options(_voices(answers['/voices']['data']), ('data',))
    else:
        result['warnings'].append('Voice discovery unavailable; your saved voice is unchanged.')
    if ok('/tuning/profiles') and isinstance(answers['/tuning/profiles']['data'], dict):
        result['tuning'] = options(answers['/tuning/profiles']['data'], ('profiles',))
        server = {**(server or {}), 'tuning': _tuning(answers['/tuning/profiles']['data'])}
    if server is not None:
        result['server'] = {'model': '', 'loaded': False, 'state': '', 'tuning': None, **server}
    route = answers.get('/audio/speech', {}).get('status')
    model = role.get('model') or ''
    listed = {item['id'] for item in models}
    if route == 404:
        undocumented = ' No documented OpenAI-style speech route was found for ' + label + ': Convo cannot speak through it until the server offers one.' if provider in ('llamacpp', 'unsloth_studio') else ''
        return {'state': 'unverified', 'message': label + ' answered, but has no speech route at ' + urlsplit(url).path + '/audio/speech (HTTP 404).' + undocumented}
    if route not in ROUTE_PRESENT:
        return {'state': 'unverified', 'message': 'The server answered, but its speech route could not be checked' +
                (' (HTTP ' + str(route) + ').' if route else '.') + ' ' + NO_AUDIO}
    if not model:
        return {'state': 'unverified', 'message': 'The server has a speech route. Choose a model.'}
    if listed and model not in listed:
        return {'state': 'unverified', 'message': 'Endpoint responded; saved model is not listed. Its selection was preserved.'}
    if server and server.get('model') is not None and 'loaded' in server and not (server['loaded'] and server['model'] == model):
        has = (server['model'] + ' loaded') if server['loaded'] and server['model'] else 'no model loaded'
        return {'state': 'unverified', 'message': 'Your server lists ' + model + ' but has ' + has + '. Load it in your server’s own Voice Studio: '
                                                  'Convo never loads, switches or unloads models on your server.'}
    return {'state': 'ready', 'message': 'The server answered, has a speech route and lists the selected model. ' + NO_AUDIO}
